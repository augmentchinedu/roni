/**
 * scripts/embed-compositor.mjs
 *
 * Reads compositor/dist/ and generates kernel/compositor-embedded.js
 * which exports a Map of { path -> Buffer } for all files.
 *
 * The compositor HTTP server then serves from memory instead of disk.
 */

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(fileURLToPath(import.meta.url), '../..')
const DIST = join(ROOT, 'compositor', 'dist')
const OUT  = join(ROOT, 'kernel', 'compositor-embedded.js')

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) walk(full, files)
    else files.push(full)
  }
  return files
}

const files = walk(DIST)
const entries = files.map(f => {
  const rel  = '/' + relative(DIST, f).replace(/\\/g, '/')
  const data = readFileSync(f).toString('base64')
  return `  ${JSON.stringify(rel)}: Buffer.from(${JSON.stringify(data)}, 'base64')`
})

const out = `// AUTO-GENERATED by scripts/embed-compositor.mjs — do not edit
export const compositorFiles = {
${entries.join(',\n')}
};
`

writeFileSync(OUT, out)
console.log(`[embed] Embedded ${files.length} files → kernel/compositor-embedded.js`)
